// Copies the Go server's web/ shell and theme into this Worker, so web/ stays
// the single source of truth:
//
//   dist/public/assets/*      static assets (app.js, app.css, theme files)
//   dist/public/_headers      security headers for those assets
//   src/generated/web.ts      templates and theme files the Worker renders
//
// GLASSHELF_THEME picks a built-in theme (default, terminal, paper) and
// GLASSHELF_THEME_DIR a directory overriding theme and shell files, like the Go
// server's --theme and --theme-dir.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const web = resolve(root, '..', 'web');
const theme = process.env.GLASSHELF_THEME || 'default';
const themeDir = process.env.GLASSHELF_THEME_DIR ? resolve(process.env.GLASSHELF_THEME_DIR) : '';

if (!existsSync(join(web, 'themes', theme, 'theme.css')) && theme !== 'default') {
  console.error(`unknown theme ${JSON.stringify(theme)}; built-in themes: ${readdirSync(join(web, 'themes')).join(', ')}`);
  process.exit(1);
}

// Same lookup order as the Go server's themeFile and shellFile.
function themeFile(name) {
  for (const dir of [themeDir, join(web, 'themes', theme), join(web, 'themes', 'default')]) {
    if (dir && existsSync(join(dir, name))) return readFileSync(join(dir, name));
  }
  throw new Error(`theme file ${name} not found`);
}
function shellFile(name) {
  if (themeDir && existsSync(join(themeDir, name))) return readFileSync(join(themeDir, name));
  return readFileSync(join(web, name));
}

const out = join(root, 'dist', 'public');
rmSync(join(root, 'dist'), { recursive: true, force: true });
mkdirSync(join(out, 'assets'), { recursive: true });

// Theme files served at /assets/<name>. design.md and template.html are
// served by the Worker (/design.md, /template.html), not as static assets.
const names = new Set();
for (const dir of [join(web, 'themes', 'default'), join(web, 'themes', theme), themeDir]) {
  if (!dir || !existsSync(dir)) continue;
  for (const n of readdirSync(dir)) {
    if (/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(n) && statSync(join(dir, n)).isFile()) names.add(n);
  }
}
for (const n of ['app.js', 'app.css', 'index.html', 'share.html', 'design.md', 'template.html', 'embed.go']) names.delete(n);
for (const n of names) writeFileSync(join(out, 'assets', n), themeFile(n));
writeFileSync(join(out, 'assets', 'app.js'), shellFile('app.js'));
writeFileSync(join(out, 'assets', 'app.css'), shellFile('app.css'));

// Matches the headers the Go server puts on /assets/* responses.
writeFileSync(join(out, '_headers'), `/assets/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  X-Robots-Tag: noindex, nofollow
  X-Frame-Options: DENY
  Content-Security-Policy: default-src 'none'; style-src 'unsafe-inline'; frame-ancestors 'none'
  Cache-Control: no-cache
`);

const gen = join(root, 'src', 'generated');
mkdirSync(gen, { recursive: true });
const str = (b) => JSON.stringify(b.toString('utf8'));
writeFileSync(join(gen, 'web.ts'), `// Generated by scripts/build-web.mjs from ../web (theme ${JSON.stringify(theme)}). Do not edit.
export const INDEX_HTML = ${str(shellFile('index.html'))};
export const SHARE_HTML = ${str(shellFile('share.html'))};
export const DESIGN_MD = ${str(themeFile('design.md'))};
export const TEMPLATE_HTML = ${str(themeFile('template.html'))};
export const MARKDOWN_CSS = ${str(themeFile('markdown.css'))};
export const THEME = ${JSON.stringify(theme)};
`);
console.log(`built web assets (theme ${theme}${themeDir ? ', theme dir ' + themeDir : ''}): ${[...names, 'app.js', 'app.css'].join(', ')}`);
